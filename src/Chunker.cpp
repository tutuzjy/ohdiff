std::tuple<uint64_t, size_t> cut(const uint8_t* source, size_t sourceLen, size_t minSize, size_t avgSize,
                                 size_t maxSize, uint64_t maskS, uint64_t maskL, uint64_t maskSLs, uint64_t maskLLs)
{
    size_t remaining = sourceLen;
    if (remaining <= minSize) {
        return {0, remaining};
    }
    size_t center = avgSize;
    if (remaining > maxSize) {
        remaining = maxSize;
    } else if (remaining < center) {
        center = remaining;
    }
    constexpr size_t rollingBytes = 2;
    size_t index = minSize / rollingBytes;
    uint64_t hash = 0;
    while (index < center / rollingBytes) {
        size_t a = index * rollingBytes;
        hash = (hash << rollingBytes) + GEAR_LS[source[a]];
        if ((hash & maskSLs) == 0) {
            return {hash, a};
        }
        hash += GEAR[source[a + 1]];
        if ((hash & maskS) == 0) {
            return {hash, a + 1};
        }
        index += 1;
    }
    while (index < remaining / rollingBytes) {
        size_t a = index * rollingBytes;
        hash = (hash << rollingBytes) + GEAR_LS[source[a]];
        if ((hash & maskLLs) == 0) {
            return {hash, a};
        }
        hash += GEAR[source[a + 1]];
        if ((hash & maskL) == 0) {
            return {hash, a + 1};
        }
        index += 1;
    }
    return {hash, remaining};
}

uint32_t normalization_bits(Normalization level)
{
    if (level > Normalization::Level3) {
        throw std::invalid_argument("Invalid FastCDC normalization level");
    }
    return static_cast<uint32_t>(level);
}

StreamCDC::StreamCDC(std::istream& source, uint32_t minSize, uint32_t avgSize, uint32_t maxSize, Normalization level)
    : buffer(maxSize), capacity(maxSize), length(0), source(source), processed(0), minSize(minSize), avgSize(avgSize),
      maxSize(maxSize)
{
    if (minSize < MINIMUM_MIN || minSize > MINIMUM_MAX || avgSize < AVERAGE_MIN || avgSize > AVERAGE_MAX ||
        maxSize < MAXIMUM_MIN || maxSize > MAXIMUM_MAX || minSize > avgSize || avgSize > maxSize ||
        maxSize > CHUNK_MAX_SIZE) {
        throw std::invalid_argument("Invalid FastCDC chunk size limits");
    }

    auto bits = Logarithm2(avgSize);
    auto normalization = normalization_bits(level);
    maskS = MASKS[bits + normalization];
    maskL = MASKS[bits - normalization];
    maskSLs = maskS << 1;
    maskLLs = maskL << 1;
}

size_t StreamCDC::fill_buffer()
{
    if (source.eof()) {
        return 0;
    } else {
        size_t all_bytes_read = 0;
        while (!source.eof() && length < capacity) {
            source.read(reinterpret_cast<char*>(buffer.data()) + length, capacity - length);
            size_t bytes_read = source.gcount();

            if (source.bad() || (source.fail() && !source.eof())) {
                throw std::runtime_error("Failed to read chunk source");
            }
            length += bytes_read;
            all_bytes_read += bytes_read;
        }
        return all_bytes_read;
    }
}

void StreamCDC::drain_bytes_to_buffer(uint8_t* dst, size_t count)
{
    if (count > length || count > CHUNK_MAX_SIZE || (count != 0 && dst == nullptr)) {
        throw std::runtime_error(
            fmt::format("drain_bytes() called with count larger than length: {} > {}", count, length));
    } else {
        std::copy_n(buffer.begin(), count, dst);
        std::move(buffer.begin() + count, buffer.begin() + length, buffer.begin());
        length -= count;
    }
}

bool StreamCDC::next_chunk_no_alloc(ChunkData& chunk)
{
    fill_buffer();
    if (length == 0) [[unlikely]] {
        return false;
    }

    auto [hash, count] = cut(buffer.data(), length, minSize, avgSize, maxSize, maskS, maskL, maskSLs, maskLLs);
    if (count == 0) [[unlikely]] {
        return false;
    }

    auto offset = processed;
    processed += count;
    chunk.hash = hash;
    chunk.offset = offset;
    chunk.length = count;
    drain_bytes_to_buffer(chunk.data, count);

    return true;
}
